# ============================================================================
# 完整注入函数
# ============================================================================

def build_brain_system_prompt(
    brain_id: str = None,
    brain_config = None,
    include_paywall: bool = True,
) -> str:
    """
    构建完整的 Brain System Prompt

    Args:
        brain_id: 大脑 ID（可选）
        brain_config: BrainConfig 对象（如果已加载）
        include_paywall: 是否包含付费突破策略

    Returns:
        完整的 system_prompt 字符串
    """
    parts = ["# 玄枢 AI — 运行时行为规范", ""]

    # 基础规则
    parts.append(BRAIN_ACTIVATION_RULES)

    if include_paywall:
        parts.append(PAYWALL_BREAKTHROUGH_RULES)

    parts.append(TOOL_SAFETY_RULES)

    # 特定大脑的附加规则
    if brain_config is not None:
        parts.append("")
        parts.append("---")
        parts.append("")
        parts.append(f"## 当前激活大脑：{brain_config.name}")
        parts.append("")
        parts.append(brain_config.to_prompt())
    elif brain_id:
        parts.append("")
        parts.append(f"## 建议激活大脑：{brain_id}")

    return "\n".join(parts)


def build_minimal_rules() -> str:
    """构建最小规则集（无大脑激活时的默认规则）"""
    return "\n".join([
        "# 玄枢 AI — 默认行为规范",
        "",
        TOOL_SAFETY_RULES,
    ])
